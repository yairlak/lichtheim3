# Step 2: GloVe coverage
# ---------------------------------------------------------------------------

def glove_coverage(df: pd.DataFrame, glove_path: str) -> dict:
    print(f"[glove] Loading {glove_path} word index …")
    glove_words: set[str] = set()
    with open(glove_path, "r", encoding="utf-8") as f:
        for line in f:
            word = line.split(" ", 1)[0]
            glove_words.add(word)
    print(f"  {len(glove_words)} GloVe vocab entries loaded")

    df = df.copy()
    df["has_glove"] = df["word"].isin(glove_words)

    n_total    = len(df)
    n_covered  = int(df["has_glove"].sum())
    n_missing  = n_total - n_covered
    pct        = round(100.0 * n_covered / max(n_total, 1), 2)

    missing_df = df[~df["has_glove"]][["rank", "word"]].reset_index(drop=True)

    # Coverage by scale
    cov = {}
    for cap in (1000, 5000, 10000, 20000, 30000):
        sub = df[df["rank"] <= cap]
        cov[str(cap)] = {
            "total":   len(sub),
            "covered": int(sub["has_glove"].sum()),
            "pct":     round(100.0 * sub["has_glove"].sum() / max(len(sub), 1), 2),
        }

    # Maximum N such that all words 1..N have GloVe
    # Sort by rank and find first gap
    sorted_df = df.sort_values("rank")
    max_prefix = 0
    for _, row in sorted_df.iterrows():
        if row["has_glove"]:
            max_prefix = int(row["rank"])
        else:
            break

    report = {
        "glove_path":     glove_path,
        "glove_vocab_size": len(glove_words),
        "n_total":         n_total,
        "n_covered":       n_covered,
        "n_missing":       n_missing,
        "coverage_pct":    pct,
        "coverage_by_scale": cov,
        "max_contiguous_prefix": max_prefix,
        "all_30k_covered": n_missing == 0,
        "first_100_missing": missing_df.head(100).to_dict(orient="records"),
    }
    print(f"  coverage: {n_covered}/{n_total} ({pct}%)  "
          f"max contiguous prefix: {max_prefix}  "
          f"30k all covered: {report['all_30k_covered']}")
    return report, missing_df


