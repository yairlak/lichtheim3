# main
# ---------------------------------------------------------------------------

def main():
    args = parse_args()
    os.makedirs(args.out_dir, exist_ok=True)

    vocab = build_vocab()
    vocab_set = set(vocab.itos[3:])   # skip PAD/BOS/EOS

    # ---- Step 1: lexicon audit ----
    print("\n=== Step 1: Lexicon audit ===")
    lex_report, df = audit_lexicon(args.lexicon, vocab_set)

    lex_json = os.path.join(args.out_dir, "lichtheim3_lexicon_audit.json")
    with open(lex_json, "w") as f:
        json.dump(lex_report, f, indent=2, default=str)
    print(f"  -> {lex_json}")

    lex_md = os.path.join(args.out_dir, "lichtheim3_lexicon_audit.md")
    write_lexicon_audit_md(lex_report, lex_md)

    # ---- Step 2: GloVe coverage ----
    print("\n=== Step 2: GloVe coverage ===")
    if not os.path.exists(args.glove):
        print(
            f"\n  *** GloVe file NOT FOUND: {args.glove} ***\n"
            "  GloVe is required for scale-up training with real semantic targets.\n"
            "  Run:  bash data/get_glove.sh\n"
            "  Then re-run this script.\n"
            "  (GloVe audit skipped — lexicon audit above is still valid.)"
        )
        return

    glove_report, missing_df = glove_coverage(df, args.glove)

    glove_json = os.path.join(args.out_dir, "glove_coverage_lexicon_en.json")
    with open(glove_json, "w") as f:
        json.dump(glove_report, f, indent=2, default=str)
    print(f"  -> {glove_json}")

    glove_md = os.path.join(args.out_dir, "glove_coverage_lexicon_en.md")
    write_glove_coverage_md(glove_report, glove_md)

    if len(missing_df) > 0:
        miss_tsv = os.path.join(args.out_dir, "missing_glove_words.tsv")
        missing_df.to_csv(miss_tsv, sep="\t", index=False)
        print(f"  -> {miss_tsv}  ({len(missing_df)} words)")

    print("\n=== Audit complete ===")


if __name__ == "__main__":
    main()
