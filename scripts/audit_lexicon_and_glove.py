    for n, d in report["coverage_by_scale"].items():
        lines.append(f"| {int(n):,} | {d['total']} | {d['covered']} | {d['pct']}% |")

    lines += [
        "",
        "## First 20 missing words",
        "",
        "| Rank | Word |",
        "|---|---|",
    ]
    for item in report["first_100_missing"][:20]:
        lines.append(f"| {item['rank']} | {item['word']} |")

