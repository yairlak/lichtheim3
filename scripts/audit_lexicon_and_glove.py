"""Steps 1 & 2: Audit lexicon_en.tsv and GloVe coverage.

Run before any scale-up training.

Outputs:
    outputs/scale_up_data_audit/lichtheim3_lexicon_audit.json
    outputs/scale_up_data_audit/lichtheim3_lexicon_audit.md
    outputs/scale_up_data_audit/glove_coverage_lexicon_en.json
    outputs/scale_up_data_audit/glove_coverage_lexicon_en.md
    outputs/scale_up_data_audit/missing_glove_words.tsv   (only if GloVe present)

Usage:
    python scripts/audit_lexicon_and_glove.py
    python scripts/audit_lexicon_and_glove.py --lexicon data/lexicon_en.tsv

If data/glove.6B.300d.txt is absent the GloVe section is skipped with a clear
message instructing the user to run:
    bash data/get_glove.sh
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from collections import Counter

import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)

from data.phonemes import build_vocab, PHONEMES

LEX_DEFAULT  = os.path.join(ROOT, "data", "lexicon_en.tsv")
GLOVE_PATH   = os.path.join(ROOT, "data", "glove.6B.300d.txt")
OUT_DIR      = os.path.join(ROOT, "outputs", "scale_up_data_audit")


def parse_args():
    p = argparse.ArgumentParser()
    p.add_argument("--lexicon", default=LEX_DEFAULT)
    p.add_argument("--glove",   default=GLOVE_PATH)
    p.add_argument("--out_dir", default=OUT_DIR)
    return p.parse_args()


# ---------------------------------------------------------------------------
# Step 1: lexicon audit
# ---------------------------------------------------------------------------

def audit_lexicon(tsv_path: str, vocab_set: set) -> dict:
    print(f"[audit] Reading {tsv_path} …")
    df = pd.read_csv(tsv_path, sep="\t",
                     names=["rank", "word", "arpabet"],
                     header=0, dtype={"rank": int, "word": str, "arpabet": str})

    n_rows      = len(df)
    rank_min    = int(df["rank"].min())
    rank_max    = int(df["rank"].max())

    # Phoneme length distribution
    df["phones"]  = df["arpabet"].apply(lambda s: s.split())
    df["n_phones"]= df["phones"].apply(len)
    length_dist   = df["n_phones"].value_counts().sort_index().to_dict()

    # Phoneme inventory coverage
    all_phones  = set(p for seq in df["phones"] for p in seq)
    unknown     = sorted(all_phones - vocab_set)
    not_in_lex  = sorted(vocab_set - all_phones)

    # Duplicate words
    dup_words   = df[df.duplicated("word", keep=False)]["word"].tolist()

    # Duplicate phoneme sequences
    df["phones_key"] = df["phones"].apply(tuple)
    dup_phones  = df[df.duplicated("phones_key", keep=False)]["word"].tolist()

    # Lowercase alphabetic check
    non_alpha   = df[~df["word"].str.isalpha()]["word"].tolist()
    non_lower   = df[df["word"] != df["word"].str.lower()]["word"].tolist()

    # Suspicious entries: very short words, very long phoneme sequences
    very_short  = df[df["n_phones"] < 2]["word"].tolist()
    very_long   = df[df["n_phones"] > 9]["word"].tolist()

    report = {
        "lexicon_path":    tsv_path,
        "n_rows":          n_rows,
        "columns":         ["rank", "word", "arpabet"],
        "rank_range":      [rank_min, rank_max],
        "length_distribution": {str(k): v for k, v in length_dist.items()},
        "mean_phoneme_length": round(float(df["n_phones"].mean()), 2),
        "phoneme_inventory": {
            "total_unique_phonemes_in_tsv": len(all_phones),
            "lichtheim3_vocab_size":        len(vocab_set),
            "phonemes_in_tsv_not_in_vocab": unknown,
            "lichtheim3_phonemes_not_in_tsv": not_in_lex,
        },
        "duplicate_words":    len(dup_words),
        "dup_word_examples":  dup_words[:20],
        "duplicate_phoneme_seqs": len(dup_phones),
        "dup_phones_examples":    dup_phones[:20],
        "non_alphabetic_words": len(non_alpha),
        "non_lowercase_words":  len(non_lower),
        "non_alpha_examples":   non_alpha[:20],
        "words_with_n_phones_below_2": len(very_short),
        "words_with_n_phones_above_9": len(very_long),
        "above_9_examples": very_long[:20],
        "availability": {
            "available_10k":  int((df["rank"] <= 10000).sum()),
            "available_20k":  int((df["rank"] <= 20000).sum()),
            "available_30k":  int((df["rank"] <= 30000).sum()),
        },
    }
    print(f"  {n_rows} rows  rank {rank_min}–{rank_max}  "
          f"phoneme lengths {min(length_dist)}-{max(length_dist)}  "
          f"unknown phones: {unknown or 'none'}")
    return report, df


